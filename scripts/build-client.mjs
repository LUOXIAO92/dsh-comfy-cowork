/**
 * Build the browser bundle.
 *
 * DSH loads a Client module from `window.__ModuleLoader__.load({ id, factory })`,
 * so the esbuild CJS output is wrapped in that factory and React is resolved
 * through the loader's `require` (never bundled twice).
 */
import { build } from 'esbuild'
import { readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)))
const pkg = JSON.parse(await readFile(path.join(root, 'package.json'), 'utf8'))

const result = await build({
  entryPoints: [path.join(root, 'src/client/entry.jsx')],
  bundle: true,
  write: false,
  format: 'cjs',
  platform: 'browser',
  target: ['chrome120'],
  external: ['react'],
  jsx: 'transform',
  jsxFactory: 'React.createElement',
  jsxFragment: 'React.Fragment',
  loader: { '.css': 'text' },
  legalComments: 'none',
  minify: false,
  sourcemap: false,
})

const code = result.outputFiles[0].text
const wrapped = `/* ${pkg.name} client bundle — generated by scripts/build-client.mjs; edit src/client instead. */
window.__ModuleLoader__.load({
  id: ${JSON.stringify(pkg.name)},
  factory(require) {
    const module = { exports: {} };
    (function (module, exports, require) {
${code}
    })(module, module.exports, require);
    return module.exports;
  }
});
`
await writeFile(path.join(root, 'client.js'), wrapped, 'utf8')
console.log(`built client.js (${Buffer.byteLength(wrapped)} bytes)`)
