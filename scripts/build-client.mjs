/**
 * Build the browser bundle.
 *
 * DSH loads a Client module from `window.__ModuleLoader__.load({ id, factory })`,
 * so the esbuild CJS output is wrapped in that factory and React is resolved
 * through the loader's `require` (never bundled twice).
 */
import { build } from 'esbuild'
import { readdir, readFile, writeFile } from 'node:fs/promises'
import { createHash } from 'node:crypto'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)))
const pkg = JSON.parse(await readFile(path.join(root, 'package.json'), 'utf8'))

// Stamp the bundle so a page running an older build is identifiable from the
// host's diagnostics instead of being inferred from what the UI looks like.
const clientDir = path.join(root, 'src/client')
const sources = (await readdir(clientDir)).filter((name) => /\.(jsx?|css)$/.test(name)).sort()
const stamp = createHash('sha256')
for (const name of sources) {
  stamp.update(name).update(await readFile(path.join(clientDir, name)))
}
const buildStamp = stamp.digest('hex').slice(0, 10)

const result = await build({
  entryPoints: [path.join(root, 'src/client/entry.jsx')],
  bundle: true,
  write: false,
  format: 'cjs',
  platform: 'browser',
  target: ['chrome120'],
  external: ['react'],
  jsx: 'transform',
  jsxFactory: 'React.createElement',
  jsxFragment: 'React.Fragment',
  loader: { '.css': 'text' },
  legalComments: 'none',
  minify: false,
  sourcemap: false,
  define: { __CCW_BUILD__: JSON.stringify(buildStamp) },
})

const code = result.outputFiles[0].text
const wrapped = `/* ${pkg.name} client bundle — build ${buildStamp} — generated by scripts/build-client.mjs; edit src/client instead. */
window.__ModuleLoader__.load({
  id: ${JSON.stringify(pkg.name)},
  factory(require) {
    const module = { exports: {} };
    (function (module, exports, require) {
${code}
    })(module, module.exports, require);
    return module.exports;
  }
});
`
await writeFile(path.join(root, 'client.js'), wrapped, 'utf8')
console.log(`built client.js (${Buffer.byteLength(wrapped)} bytes, build ${buildStamp})`)
